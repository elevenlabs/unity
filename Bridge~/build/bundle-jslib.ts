// Bundle a TypeScript entry into a Unity .jslib file.
//
// Usage:
//   node build/bundle-jslib.ts <entry.ts> <output.jslib> [--mode <iife|postset>]
//
// Run directly with Node 23+ (which strips TS types natively, no transpile
// step). Two emit modes are supported:
//
// `iife` (default; used for `src/primitives/`):
//   The TS entry default-exports the library object — the same shape that
//   would otherwise be passed inline to `mergeInto`. Rolldown wraps the
//   output in an IIFE that returns that object, and the footer wires it into
//   `LibraryManager.library`. Each property becomes a discrete Emscripten
//   library entry that Emscripten emits as a top-level `var` / `function` in
//   framework.js. Works only when every entry is self-contained (no
//   closures over bundle-internal helpers that aren't also library entries).
//
// `postset` (used for `src/connection/`):
//   The TS entry is bundled to plain ES module output. The bundler then
//   embeds the entire compiled source as a JSON-escaped string and emits a
//   single `$EL_<Name>Init` library entry whose value is `';' + bundleSource`.
//   Emscripten's `;`-prefix path (jsifier.js: `var ' + mangled + snippet`)
//   then writes the bundle verbatim into framework.js at top scope. Every
//   symbol the bundle declares — SDK classes, helpers, factory registrations,
//   side-effects — lands in runtime scope, instead of being trapped inside
//   an IIFE whose body Emscripten drops on the floor. See
//   Docs~/plans/jslib-bundler-iife-scope.md.
//
// The `--mode` flag has no default per se; if omitted, the script picks
// `iife` for back-compat with the primitives build.

import { rolldown, type OutputChunk } from "rolldown";
import { writeFile } from "node:fs/promises";
import { basename, dirname, relative, resolve } from "node:path";
import { lowerDestructuring } from "./lower-destructuring.ts";
import { substituteMakeDyncall } from "./substitute-make-dyncall.ts";

type Mode = "iife" | "postset";

interface ParsedArgs {
  entry: string;
  output: string;
  mode: Mode;
}

function parseArgs(argv: readonly string[]): ParsedArgs {
  const positional: string[] = [];
  let mode: Mode = "iife";
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--mode") {
      const next = argv[++i];
      if (next !== "iife" && next !== "postset") {
        throw new Error(
          `--mode must be 'iife' or 'postset', got '${next ?? ""}'.`,
        );
      }
      mode = next;
    } else if (a.startsWith("--mode=")) {
      const value = a.slice("--mode=".length);
      if (value !== "iife" && value !== "postset") {
        throw new Error(`--mode must be 'iife' or 'postset', got '${value}'.`);
      }
      mode = value;
    } else {
      positional.push(a);
    }
  }
  if (positional.length !== 2) {
    throw new Error(
      "Usage: bundle-jslib.ts <entry.ts> <output.jslib> [--mode <iife|postset>]",
    );
  }
  return {
    entry: resolve(positional[0]),
    output: resolve(positional[1]),
    mode,
  };
}

function makeBanner(entry: string): string {
  const repoRoot = resolve(import.meta.dirname, "..", "..");
  const sourceDir = relative(repoRoot, dirname(entry));
  const bundleName = sourceDir.split("/").at(-1) ?? "bundle";
  return (
    "// Generated by Bridge~/build/bundle-jslib.ts — do not edit by hand.\n" +
    `// Source: ${sourceDir}/. Regenerate via \`pnpm run build:${bundleName}\`.\n\n`
  );
}

// Renders an IIFE-format bundle whose returned `library` object is then handed
// to `mergeInto`. Each library entry must be self-contained or rely only on
// other library entries — see file header.
function renderIife(chunk: OutputChunk): string {
  const footer = "\nmergeInto(LibraryManager.library, library);\n";
  return chunk.code + footer;
}

// Renders the connection-style bundle: the entire ES module output is JSON-
// stringified and emitted as the value of a single `$EL_<Name>Init` library
// entry. The `;`-prefix is what makes Emscripten emit the bundle source
// verbatim at framework.js top scope (jsifier.js handling for
// `var <mangled>;<code>;` — see Docs~/plans/jslib-bundler-iife-scope.md).
//
// The bundle is responsible for self-registering with the primitives layer
// (via `EL_RegisterFactory` calls in the bundled code), so no factory entries
// are surfaced as separate library variables.
function renderPostset(chunk: OutputChunk, entry: string): string {
  const initName = pascalInitName(entry);
  // JSON.stringify produces a valid JS string literal for the bundle source,
  // including all newline / quote / backslash escapes. The `;` prefix puts
  // Emscripten into its verbatim-emit path (`var <name>;<code>;` — see
  // emscripten/src/jsifier.js).
  const escaped = JSON.stringify(";" + chunk.code);
  // The C-callable `EL_EnsureConnectionFactoriesLoaded` exists only so a
  // DllImport on the C# side can pin `$EL_ConnectionInit` into the linked
  // build. Emscripten would otherwise strip the whole entry — including its
  // bundle payload — because no library function depends on it. The function
  // body is intentionally empty; reachability is the entire point. See
  // Runtime/WebGL/Bridged/BridgedSessionLauncher.cs for the C# call site
  // and Docs~/plans/jslib-bundler-iife-scope.md for the rationale.
  return `mergeInto(LibraryManager.library, {
  $${initName}__deps: ["$EL_RegisterFactory"],
  $${initName}: ${escaped},

  EL_EnsureConnectionFactoriesLoaded__deps: ["$${initName}"],
  EL_EnsureConnectionFactoriesLoaded: function () {},
});
`;
}

// Derives a PascalCase init-entry name from the entry path:
//   src/connection/index.ts → EL_ConnectionInit
//   src/foo-bar/index.ts    → EL_FooBarInit
// The result is what Emscripten emits as the runtime `var <name>;` declaration.
function pascalInitName(entry: string): string {
  const dir = basename(dirname(entry));
  const pascal = dir
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return `EL_${pascal}Init`;
}

const { entry, output, mode } = parseArgs(process.argv.slice(2));

// `lowerDestructuring` only matters in postset mode: Emscripten's JSDCE pass
// runs over the postset string verbatim and incorrectly strips destructuring
// declarations whose RHS is side-effect-free (see lower-destructuring.ts).
// The primitives bundle keeps its hand-authored library entries and never
// produces destructuring patterns through that path, so skipping the plugin
// there preserves the existing byte-stable primitives `.jslib`.
const plugins =
  mode === "postset"
    ? [substituteMakeDyncall(), lowerDestructuring()]
    : [substituteMakeDyncall()];

const bundle = await rolldown({
  input: entry,
  plugins,
  // Postset mode emits the bundle verbatim at framework.js top scope. Two
  // separate Emscripten limitations apply there:
  //
  //   * The shipped acorn predates ES2021 logical-assignment (`??=`, `||=`,
  //     `&&=`) and dies with "SyntaxError: Unexpected token" if any reaches
  //     the link step.
  //   * The shipped terser predates the ES2020 `ChainExpression` AST node
  //     (the wrapper acorn emits around `a?.b.c`) — its Mozilla→Terser AST
  //     converter has no entry for it and throws
  //     "MOZ_TO_ME[node.type] is not a function" mid-DCE.
  //
  // Lowering to ES2019 removes both. We only apply it in postset mode: the
  // iife (primitives) build's library entries are hand-authored to avoid
  // both features already, and skipping lowering there keeps the committed
  // primitives `.jslib` byte-for-byte stable across rebuilds.
  ...(mode === "postset" ? { transform: { target: "es2019" } } : {}),
});

try {
  const { output: chunks } = await bundle.generate({
    // `iife` mode uses Rolldown's IIFE wrapping (returns the library object).
    // `postset` mode uses ESM output so symbols are at the bundle's top
    // scope — the wrapper that Emscripten emits is what puts them at runtime
    // top scope.
    format: mode === "iife" ? "iife" : "es",
    ...(mode === "iife"
      ? { name: "library", exports: "default" as const }
      : {}),
    minify: false,
  });

  const chunk = chunks.find((c): c is OutputChunk => c.type === "chunk");
  if (!chunk) {
    console.error("No chunk produced by Rolldown");
    process.exit(1);
  }

  const banner = makeBanner(entry);
  const body =
    mode === "iife" ? renderIife(chunk) : renderPostset(chunk, entry);

  await writeFile(output, banner + body);
  console.log("Wrote", output);
} finally {
  await bundle.close();
}
