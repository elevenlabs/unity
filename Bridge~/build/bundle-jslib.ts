// Bundle a TypeScript entry into a Unity .jslib file.
//
// Usage: node build/bundle-jslib.ts <entry.ts> <output.jslib>
//
// Run directly with Node 23+ (which strips TS types natively, no transpile step).
// The TS entry must default-export the library object (the same shape that
// would otherwise be passed inline to mergeInto). This script bundles it via
// Rolldown's IIFE format so the result is a single self-contained file that
// Emscripten's jslib loader can execute at Unity build time.

import { rolldown } from "rolldown";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = process.argv.slice(2);
if (args.length !== 2) {
  console.error("Usage: bundle-jslib.ts <entry.ts> <output.jslib>");
  process.exit(1);
}
const [entry, output] = args.map((p) => resolve(p));

const bundle = await rolldown({ input: entry });

try {
  const { output: chunks } = await bundle.generate({
    format: "iife",
    name: "library",
    exports: "default",
    minify: false,
  });

  const chunk = chunks.find((c) => c.type === "chunk");
  if (!chunk) {
    console.error("No chunk produced by Rolldown");
    process.exit(1);
  }

  // Footer wires the IIFE result into Unity's library object. Kept as a literal
  // mergeInto call so Emscripten's jslib loader sees the exact pattern it
  // expects when it evaluates the file at build time.
  const banner =
    "// Generated by Bridge~/build/bundle-jslib.ts — do not edit by hand.\n" +
    "// Source: Bridge~/src/primitives/. Regenerate via `pnpm run build:primitives`.\n\n";
  const footer = "\nmergeInto(LibraryManager.library, library);\n";

  await writeFile(output, banner + chunk.code + footer);
  console.log("Wrote", output);
} finally {
  await bundle.close();
}
